% Etapa 11 independent MATLAB R2022b reference verification script
% Verifies:
% 1. Section 1 audit table: exact damping ratio xi of all 5 Etapa 10 refined controllers (both full f64 & 4-decimal rounded gains)
% 2. All Etapa 11 constrained controllers (exact xi=0.4 on Q5, exact xi=0.5 on Q2 PID, exact xi=0.50+-0.01 dominant on Q7 PD,
%    and xi>=0.5 solutions on Q2 PD, Q8 PI, Q9 PD) including exact Heaviside modal residue ratios
% 3. Q5 exact xi=0.4 perturbation robustness (+/-5% and +/-10% on plant gain and denominator)

s = tf('s');
out = struct();
out.matlab_version = version;

% Helper function via anonymous/nested evaluation:
% 1. Etapa 10 Section 1 audit (full-precision gains vs 4-decimal rounded gains)
e10_cases = { ...
    'q2_pd_e10_full',    1/(s^2+1),                   pid(6.5860656976371965, 0, 13.355570405454662); ...
    'q2_pd_e10_round',   1/(s^2+1),                   pid(6.5861, 0, 13.3556); ...
    'q2_pid_e10_full',   1/(s^2+1),                   pid(11.096658419745077, 5.285083609612153, 5.542244219291329); ...
    'q2_pid_e10_round',  1/(s^2+1),                   pid(11.0967, 5.2851, 5.5422); ...
    'q5_pid_e10_full',   1/(s^3+10*s^2+17*s+8),       pid(71.88638085895549, 35.900742386408645, 35.985636144021534); ...
    'q5_pid_e10_round',  1/(s^3+10*s^2+17*s+8),       pid(71.8864, 35.9007, 35.9856); ...
    'q7_pd_e10_full',    5/(s*(s+2)^2),               pid(0.5183391822300726, 0, 0.2680856376900818); ...
    'q7_pd_e10_round',   5/(s*(s+2)^2),               pid(0.5183, 0, 0.2681); ...
    'q9_pd_e10_full',    1/(s^2),                     pid(1.7458718774059128, 0, 2.440754756613886); ...
    'q9_pd_e10_round',   1/(s^2),                     pid(1.7459, 0, 2.4408) ...
};

e10_audit = struct();
for idx = 1:size(e10_cases, 1)
    cname = e10_cases{idx, 1};
    T = feedback(e10_cases{idx, 3} * e10_cases{idx, 2}, 1);
    ps = pole(T);
    c_idx = abs(imag(ps)) > 1e-6;
    if any(c_idx)
        cp = ps(c_idx);
        [~, best_i] = max(real(cp));
        dom_c = cp(best_i);
        xi_val = -real(dom_c) / abs(dom_c);
        wn_val = abs(dom_c);
    else
        xi_val = 1.0;
        wn_val = min(abs(real(ps)));
    end
    info = stepinfo(T);
    e10_audit.(cname) = struct( ...
        'xi', xi_val, ...
        'wn', wn_val, ...
        'overshoot', info.Overshoot, ...
        'settling_time', info.SettlingTime, ...
        'poles_re', real(ps).', ...
        'poles_im', imag(ps).' ...
    );
end
out.etapa10_xi_audit = e10_audit;

% 2. Etapa 11 constrained controllers
e11_cases = { ...
    'q5_pid_exact_xi04',     1/(s^3+10*s^2+17*s+8), pid(227.12265104923506, 56.86515843458203, 80.93732989873575); ...
    'q2_pid_exact_xi05',     1/(s^2+1),             pid(4.236932767669361, 4.5932785085575025, 3.765120324007892); ...
    'q7_pd_exact_xi05_dom',  5/(s*(s+2)^2),         pid(1.6029530461209025, 0, 0.8175290091906282); ...
    'q2_pd_xi_at_least',     1/(s^2+1),             pid(6.913990838235495, 0, 14.286123681380035); ...
    'q8_pi_refined_e11',     -7.2/(5*s+1),          pid(-0.5021608353065594, -0.12634484602744345, 0); ...
    'q9_pd_xi_at_least',     1/(s^2),               pid(0.10354118646519724, 0, 2.120753150278508) ...
};

e11_res = struct();
for idx = 1:size(e11_cases, 1)
    cname = e11_cases{idx, 1};
    T = feedback(e11_cases{idx, 3} * e11_cases{idx, 2}, 1);
    ps = pole(T);
    zs = zero(T);
    [num_c, den_c] = tfdata(T, 'v');
    c_idx = abs(imag(ps)) > 1e-6;
    res_ratio = NaN;
    if any(c_idx)
        cp = ps(c_idx);
        [~, best_i] = max(real(cp));
        dom_c = cp(best_i);
        xi_val = -real(dom_c) / abs(dom_c);
        wn_val = abs(dom_c);
        [r_pf, p_pf, ~] = residue(num_c, [den_c 0]);
        dom_mask = abs(real(p_pf) - real(dom_c)) < 1e-3 & abs(abs(imag(p_pf)) - abs(imag(dom_c))) < 1e-3;
        orig_mask = abs(p_pf) < 1e-6;
        other_mask = ~dom_mask & ~orig_mask;
        res_ratio = sum(abs(r_pf(other_mask))) / max(sum(abs(r_pf(dom_mask))), 1e-12);
    else
        xi_val = 1.0;
        wn_val = min(abs(real(ps)));
    end
    info = stepinfo(T);
    e11_res.(cname) = struct( ...
        'stable', all(real(ps) < 0), ...
        'xi', xi_val, ...
        'wn', wn_val, ...
        'non_dominant_residue_ratio', res_ratio, ...
        'overshoot', info.Overshoot, ...
        'settling_time', info.SettlingTime, ...
        'rise_time', info.RiseTime, ...
        'peak_time', info.PeakTime, ...
        'dcgain', dcgain(T), ...
        'poles_re', real(ps).', ...
        'poles_im', imag(ps).', ...
        'zeros_re', real(zs).', ...
        'zeros_im', imag(zs).' ...
    );
end
out.etapa11_refined = e11_res;

% 3. Q5 exact xi=0.4 perturbation robustness (+/-5% and +/-10% on plant gain)
Gc5 = pid(227.12265104923506, 56.86515843458203, 80.93732989873575);
pert_tags = {'gain_plus_5', 'gain_minus_5', 'gain_plus_10', 'gain_minus_10', 'pole1_plus_5', 'pole1_minus_5'};
pert_plants = { ...
    1.05/(s^3+10*s^2+17*s+8), ...
    0.95/(s^3+10*s^2+17*s+8), ...
    1.10/(s^3+10*s^2+17*s+8), ...
    0.90/(s^3+10*s^2+17*s+8), ...
    1/((s+1.05)^2*(s+8)), ...
    1/((s+0.95)^2*(s+8)) ...
};
q5_rob = struct();
for idx = 1:numel(pert_tags)
    Tp = feedback(Gc5 * pert_plants{idx}, 1);
    ps = pole(Tp);
    cp = ps(abs(imag(ps)) > 1e-6);
    [~, bi] = max(real(cp));
    xi_p = -real(cp(bi)) / abs(cp(bi));
    ip = stepinfo(Tp);
    q5_rob.(pert_tags{idx}) = struct( ...
        'stable', all(real(ps) < 0), ...
        'xi', xi_p, ...
        'overshoot', ip.Overshoot, ...
        'settling_time', ip.SettlingTime, ...
        'dcgain', dcgain(Tp) ...
    );
end
out.q5_exact_robustness = q5_rob;

json_txt = jsonencode(out, 'PrettyPrint', true);
