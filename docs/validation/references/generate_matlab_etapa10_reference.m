% Etapa 10 independent MATLAB R2022b verification script
% Verifies:
% 1. Q2 classic PID (equal zeros) actual stepinfo (detecting report mismatch)
% 2. Q8 independent reference Gc(s) = -1 - 0.2/s (nominal, disturbance, +/-10% perturbations)
% 3. All Etapa 10 refined controllers (Q2 PD, Q2 PID, Q5 PID, Q7 PD, Q8 PI, Q9 PD)

s = tf('s');
results = struct();
results.matlab_version = version;

% 1. Q2 classic PID (equal zeros)
G2 = 1 / (s^2 + 1);
Gc_q2_pid = pid(3.737034183642664, 1.4740683672853223, 2.3685170918213303);
T_q2_pid = feedback(Gc_q2_pid * G2, 1);
info_q2_pid = stepinfo(T_q2_pid);
results.q2_pid_classic_equal = struct( ...
    'overshoot', info_q2_pid.Overshoot, ...
    'settling_time', info_q2_pid.SettlingTime, ...
    'rise_time', info_q2_pid.RiseTime, ...
    'peak_time', info_q2_pid.PeakTime, ...
    'dcgain', dcgain(T_q2_pid), ...
    'poles_re', real(pole(T_q2_pid)).', ...
    'poles_im', imag(pole(T_q2_pid)).', ...
    'zeros_re', real(zero(T_q2_pid)).', ...
    'zeros_im', imag(zero(T_q2_pid)).' ...
);

% 2. Q8 independent reference: G(s) = -7.2/(5s+1), Gc(s) = -1 - 0.2/s
G8 = -7.2 / (5*s + 1);
Gc8_ref = pid(-1.0, -0.2, 0);
T8_ref = feedback(Gc8_ref * G8, 1);
T8_ref_min = minreal(T8_ref);
T8_dist = feedback(G8, Gc8_ref);
info_q8_ref = stepinfo(T8_ref);
t_eval = linspace(0, 10, 2001);
y_ref = step(T8_ref, t_eval);
y_exact = 1 - exp(-1.44 * t_eval.');
y_dist = step(T8_dist, t_eval);

% Perturbation sensitivity +/-10% on gain k=-7.2 and tau=5
pert_names = {'k_plus_10', 'k_minus_10', 'tau_plus_10', 'tau_minus_10'};
pert_ks = [-7.2*1.1, -7.2*0.9, -7.2, -7.2];
pert_taus = [5.0, 5.0, 5.0*1.1, 5.0*0.9];
perts = struct();
for idx = 1:4
    Gp = pert_ks(idx) / (pert_taus(idx)*s + 1);
    Tp = feedback(Gc8_ref * Gp, 1);
    ip = stepinfo(Tp);
    perts.(pert_names{idx}) = struct( ...
        'stable', all(real(pole(Tp)) < 0), ...
        'overshoot', ip.Overshoot, ...
        'settling_time', ip.SettlingTime, ...
        'dcgain', dcgain(Tp), ...
        'poles_re', real(pole(Tp)).', ...
        'poles_im', imag(pole(Tp)).' ...
    );
end

results.q8_reference = struct( ...
    'overshoot', info_q8_ref.Overshoot, ...
    'settling_time', info_q8_ref.SettlingTime, ...
    'dcgain', dcgain(T8_ref), ...
    'disturbance_dcgain', dcgain(T8_dist), ...
    'disturbance_peak_abs', max(abs(y_dist)), ...
    'max_waveform_err_vs_analytic', max(abs(y_ref - y_exact)), ...
    'unreduced_poles_re', real(pole(T8_ref)).', ...
    'minreal_poles_re', real(pole(T8_ref_min)).', ...
    'perturbations', perts ...
);

% 3. Refined controllers (from Rust engine temporal_refined)
cases = { ...
    'q2_pd_refined', 1/(s^2 + 1), pid(6.5860656976371965, 0, 13.355570405454662); ...
    'q2_pid_refined', 1/(s^2 + 1), pid(11.096658419745077, 5.285083609612153, 5.542244219291329); ...
    'q5_pid_refined', 1/(s^3 + 10*s^2 + 17*s + 8), pid(71.88638085895549, 35.900742386408645, 35.985636144021534); ...
    'q7_pd_refined', 5/(s*(s+2)^2), pid(0.5183391822300726, 0, 0.2680856376900818); ...
    'q8_pi_refined', -7.2/(5*s + 1), pid(-0.681056036012193, -0.1362112072024386, 0); ...
    'q9_pd_refined', 1/(s^2), pid(1.7458718774059128, 0, 2.440754756613886) ...
};

refined = struct();
for idx = 1:size(cases, 1)
    cname = cases{idx, 1};
    Gp = cases{idx, 2};
    Gc = cases{idx, 3};
    T = feedback(Gc * Gp, 1);
    info = stepinfo(T);
    refined.(cname) = struct( ...
        'stable', all(real(pole(T)) < 0), ...
        'overshoot', info.Overshoot, ...
        'settling_time', info.SettlingTime, ...
        'rise_time', info.RiseTime, ...
        'peak_time', info.PeakTime, ...
        'dcgain', dcgain(T), ...
        'poles_re', real(pole(T)).', ...
        'poles_im', imag(pole(T)).', ...
        'zeros_re', real(zero(T)).', ...
        'zeros_im', imag(zero(T)).' ...
    );
end
results.refined = refined;

out_json = jsonencode(results, 'PrettyPrint', true);
fid = fopen('matlab_r2022b_etapa10_reference.json', 'w');
fwrite(fid, out_json, 'char');
fclose(fid);
fprintf('Saved matlab_etapa10_reference.json successfully.\n');
fprintf('Q2 PID classic equal: Mp=%.6f%% ts=%.6fs\n', info_q2_pid.Overshoot, info_q2_pid.SettlingTime);
fprintf('Q8 ref: Mp=%.6f%% ts=%.6fs dc=%.6f dist_dc=%.6f err=%.2e\n', ...
    info_q8_ref.Overshoot, info_q8_ref.SettlingTime, dcgain(T8_ref), dcgain(T8_dist), max(abs(y_ref - y_exact)));
